function categoryOf(key: string) {
  if (["TO_APPLY"].includes(key)) return "TO_APPLY";
  if (["PREPARING"].includes(key)) return "PREPARING";
  if (["APPLIED", "FOLLOW_UP", "APPLICATION_SUBMITTED", "WAITING"].includes(key)) return "APPLIED";
  if (key.includes("INTERVIEW")) return "INTERVIEW";
  if (["OFFER", "ADMITTED"].includes(key)) return "OFFER";
  if (key === "ACCEPTED") return "WON";
  if (["REJECTED", "WITHDRAWN", "GHOSTED", "CLOSED", "DECLINED"].includes(key)) return "LOST";
  return "BACKLOG";
}

