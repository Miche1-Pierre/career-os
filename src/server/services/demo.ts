function pdfEscape(text: string) {
  return text.replace(/[\\()]/g, (m) => `\\${m}`).replace(/[^\x20-\x7e]/g, "?");
}

export function makePdf(title: string, lines: string[]): Buffer {
  const content = [
    "BT /F1 20 Tf 60 780 Td (" + pdfEscape(title) + ") Tj ET",
    ...lines.map((line, i) => `BT /F1 11 Tf 60 ${745 - i * 18} Td (${pdfEscape(line)}) Tj ET`),
  ].join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${Buffer.byteLength(content, "latin1")} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((obj, i) => {
    offsets.push(Buffer.byteLength(pdf, "latin1"));
    pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  });
  const xref = Buffer.byteLength(pdf, "latin1");
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const off of offsets) pdf += `${String(off).padStart(10, "0")} 00000 n \n`;
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(pdf, "latin1");
}

async function demoDocument(name: string, kind: DocumentKind, versions: { fileName: string; lines: string[]; daysAgo: number; label?: string }[], today: ISODate, tags: string[] = []) {
  const [doc] = await db.insert(s.documents).values({ name, kind, tags, isDemo: true, description: "Demo document" }).returning();
  const ids: string[] = [];
  let n = 0;
  for (const v of versions) {
    n++;
    const buffer = makePdf(name, [`Version ${n} — demo file generated by Career OS`, ...v.lines]);
    const relativePath = `Demo/${v.fileName}`;
    const abs = path.join(storageConfig.dataDir, "uploads", "Demo", v.fileName);
    await fs.mkdir(path.dirname(abs), { recursive: true });
    await fs.writeFile(abs, buffer);
    const { key, checksum } = await snapshotBuffer(buffer, v.fileName);
    const created = new Date(`${addDays(today, -v.daysAgo)}T10:00:00Z`);
    const [row] = await db
      .insert(s.documentVersions)
      .values({
        documentId: doc.id,
        version: n,
        label: v.label ?? null,
        storage: "UPLOAD",
        relativePath,
        displayPath: `data/uploads/${relativePath}`,
        fileName: v.fileName,
        mimeType: "application/pdf",
        sizeBytes: buffer.byteLength,
        checksum,
        snapshotKey: key,
        fileModifiedAt: (await fs.stat(abs)).mtime,
        isDemo: true,
        createdAt: created,
      })
      .returning();
    ids.push(row.id);
  }
  return { doc, versions: ids };
}

