export async function deleteDemoData(ctx: Ctx = SYSTEM) {
  const result = await db.transaction(async (tx) => {
    const demoOpps = (await tx.select({ id: s.opportunities.id }).from(s.opportunities).where(eq(s.opportunities.isDemo, true))).map((r) => r.id);
    if (demoOpps.length) {
      await tx.delete(s.notifications).where(inArray(s.notifications.entityId, demoOpps));
      await tx.delete(s.auditLogs).where(inArray(s.auditLogs.entityId, demoOpps));
      await tx.delete(s.opportunities).where(inArray(s.opportunities.id, demoOpps));
    }
    await tx.delete(s.inboxItems).where(eq(s.inboxItems.isDemo, true));
    await tx.delete(s.goals).where(eq(s.goals.isDemo, true));
    await tx.delete(s.savedViews).where(eq(s.savedViews.isDemo, true));
    // Keep demo documents still used by real applications (adopt them), delete the rest.
    const used = await tx
      .select({ documentId: s.documentVersions.documentId })
      .from(s.opportunityDocuments)
      .innerJoin(s.documentVersions, eq(s.documentVersions.id, s.opportunityDocuments.documentVersionId));
    const usedDocs = new Set(used.map((u) => u.documentId));
    const demoDocs = await tx.select({ id: s.documents.id }).from(s.documents).where(eq(s.documents.isDemo, true));
    const deletable = demoDocs.map((d) => d.id).filter((id) => !usedDocs.has(id));
    if (deletable.length) await tx.delete(s.documents).where(inArray(s.documents.id, deletable));
    const adopted = demoDocs.map((d) => d.id).filter((id) => usedDocs.has(id));
    if (adopted.length) await tx.update(s.documents).set({ isDemo: false }).where(inArray(s.documents.id, adopted));
    // Contacts & organizations: delete unless referenced by real data.
    await tx.execute(sql`delete from contacts where is_demo and id not in (select contact_id from opportunity_contacts)`);
    await tx.execute(sql`update contacts set is_demo = false where is_demo`);
    await tx.execute(sql`delete from organizations where is_demo and id not in (select organization_id from opportunities where organization_id is not null) and id not in (select organization_id from contacts where organization_id is not null)`);
    await tx.execute(sql`update organizations set is_demo = false where is_demo`);
    await tx.execute(sql`delete from tasks where is_demo`);
    await tx.execute(sql`delete from timeline_events where is_demo`);
    return { opportunities: demoOpps.length, documents: deletable.length };
  });
  await fs.rm(path.join(storageConfig.dataDir, "uploads", "Demo"), { recursive: true, force: true }).catch(() => {});
  const onboarding = (await getSettings()).onboarding;
  await updateSettingsSection("onboarding", { ...onboarding, demoLoaded: false }, ctx);
  return result;
}

export async function hasDemoData() {
  const [row] = await db.select({ count: sql<number>`count(*)::int` }).from(s.opportunities).where(eq(s.opportunities.isDemo, true));
  return (row?.count ?? 0) > 0;
}

